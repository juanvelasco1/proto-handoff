#!/usr/bin/env node
// Turns tokens.json into a use_figma script that creates two collections:
//   Primitives — one variable per unique color value, named by hue family and lightness
//   Tokens     — the prototype's own tokens, one mode per theme, aliasing primitives
// Dimensions go into Tokens as FLOAT. Every Tokens variable carries WEB code syntax
// `var(--name)` so the Figma capture and Dev Mode map it back to the CSS custom property.
//
//   node gen-variables.mjs tokens.json > variables.figma.js
import { readFileSync } from 'node:fs';

const { themes, tokens } = JSON.parse(readFileSync(process.argv[2], 'utf8'));

// sRGB → OKLCH, only to name primitives in a way a designer can scan.
function oklch({ r, g, b }) {
  const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  const [R, G, B] = [lin(r), lin(g), lin(b)];
  const l = Math.cbrt(0.4122214708 * R + 0.5363325363 * G + 0.0514459929 * B);
  const m = Math.cbrt(0.2119034982 * R + 0.6806995451 * G + 0.1073969566 * B);
  const s = Math.cbrt(0.0883024619 * R + 0.2817188376 * G + 0.6299787005 * B);
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
  const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
  const Bb = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
  const C = Math.hypot(A, Bb);
  let H = (Math.atan2(Bb, A) * 180) / Math.PI; if (H < 0) H += 360;
  return { L, C, H };
}
const HUES = [[35, 'red'], [50, 'orange'], [75, 'amber'], [110, 'yellow'], [165, 'green'],
  [200, 'teal'], [235, 'cyan'], [275, 'blue'], [310, 'violet'], [345, 'magenta'], [361, 'red']];
function familyOf(c) {
  const { L, C, H } = oklch(c);
  const fam = C < 0.015 ? 'neutral' : HUES.find(([max]) => H < max)[1];
  return { fam, step: Math.round(L * 1000) / 10 };
}
const key = (c) => [c.r, c.g, c.b, c.a].map((x) => x.toFixed(4)).join(',');

const prims = new Map();
for (const t of tokens.filter((t) => t.type === 'color')) {
  for (const th of themes) {
    const c = t.values[th];
    if (!c || prims.has(key(c))) continue;
    const { fam, step } = familyOf(c);
    let name = `${fam}/${String(step).replace('.', '_')}`;
    if (c.a < 1) name += `-a${Math.round(c.a * 100)}`;
    let n = name, i = 2;
    while ([...prims.values()].some((p) => p.name === n)) n = `${name}-${i++}`;
    prims.set(key(c), { name: n, color: c });
  }
}

// --rail-ink → color/rail-ink ; --r-md → radius/md : one group per kind, names stay 1:1 with CSS.
function tokenPath(t) {
  const n = t.name.replace(/^--/, '');
  if (t.type === 'dimension' && /^r-/.test(n)) return `radius/${n.slice(2)}`;
  if (t.type === 'dimension') return `size/${n}`;
  return `color/${n}`;
}

const data = {
  themes,
  prims: [...prims.values()].map((p) => ({ name: p.name, rgba: Object.fromEntries(['r', 'g', 'b', 'a'].map((k) => [k, +p.color[k].toFixed(4)])) })),
  tokens: tokens.filter((t) => t.type === 'color' || t.type === 'dimension').map((t) => ({
    css: t.name,
    path: tokenPath(t),
    type: t.type,
    values: Object.fromEntries(themes.map((th) => [th,
      t.type === 'color' ? prims.get(key(t.values[th])).name : t.values[th]])),
  })),
};

process.stdout.write(`// generated by gen-variables.mjs — safe to re-run: existing collections are reused
const DATA = ${JSON.stringify(data)};
const cols = await figma.variables.getLocalVariableCollectionsAsync();
const getCol = (name) => cols.find((c) => c.name === name) || figma.variables.createVariableCollection(name);
const primCol = getCol('Primitives');
const tokCol = getCol('Tokens');
const cap = (s) => s[0].toUpperCase() + s.slice(1);
// modes: rename the default one, add the rest
tokCol.renameMode(tokCol.modes[0].modeId, cap(DATA.themes[0]));
for (const th of DATA.themes.slice(1)) if (!tokCol.modes.some((m) => m.name === cap(th))) tokCol.addMode(cap(th));
const modeId = (th) => tokCol.modes.find((m) => m.name === cap(th)).modeId;
const existing = await figma.variables.getLocalVariablesAsync();
const find = (col, name) => existing.find((v) => v.variableCollectionId === col.id && v.name === name);
const primByName = {};
for (const p of DATA.prims) {
  const v = find(primCol, p.name) || figma.variables.createVariable(p.name, primCol, 'COLOR');
  v.setValueForMode(primCol.modes[0].modeId, p.rgba);
  v.scopes = [];            // primitives are hidden from pickers: designers pick tokens
  primByName[p.name] = v;
}
const out = [];
for (const t of DATA.tokens) {
  const isColor = t.type === 'color';
  const v = find(tokCol, t.path) || figma.variables.createVariable(t.path, tokCol, isColor ? 'COLOR' : 'FLOAT');
  for (const th of DATA.themes) {
    v.setValueForMode(modeId(th), isColor
      ? figma.variables.createVariableAlias(primByName[t.values[th]])
      : t.values[th]);
  }
  v.setVariableCodeSyntax('WEB', 'var(' + t.css + ')');
  v.scopes = isColor
    ? (/ink|fg|muted|text/.test(t.css) ? ['TEXT_FILL', 'SHAPE_FILL', 'STROKE_COLOR'] : ['FRAME_FILL', 'SHAPE_FILL', 'STROKE_COLOR', 'EFFECT_COLOR'])
    : (t.path.startsWith('radius/') ? ['CORNER_RADIUS'] : ['WIDTH_HEIGHT', 'GAP']);
  out.push(v.id);
}
return { primitives: primCol.id, tokens: tokCol.id, primCount: DATA.prims.length, tokenCount: out.length,
  modes: tokCol.modes.map((m) => m.name), variableIds: out };
`);
