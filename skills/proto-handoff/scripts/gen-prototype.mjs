#!/usr/bin/env node
// Generates the use_figma script that wires the clickable prototype: one ON_CLICK → NAVIGATE
// reaction per resolved link, and one flow starting point per flow.
//
//   node gen-prototype.mjs <map-dir> <frames.json> <screensPageId> > prototype.figma.js
//
// frames.json maps screen id → frame node id (light theme frames).
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const [mapDir, framesFile, pageId] = process.argv.slice(2);
const here = path.dirname(fileURLToPath(import.meta.url));
const matcher = readFileSync(path.join(here, 'lib/figma-match.js'), 'utf8');
const frames = JSON.parse(readFileSync(framesFile, 'utf8'));
const links = JSON.parse(readFileSync(path.join(mapDir, 'links.json'), 'utf8'));
const manifest = JSON.parse(readFileSync(path.join(mapDir, 'manifest.json'), 'utf8'));

const RANK = { flow: 0, next: 1, global: 2 };
const wired = links.filter((l) => l.r && frames[l.from] && frames[l.to])
  .sort((a, b) => RANK[a.kind] - RANK[b.kind])
  .map((l) => ({ from: frames[l.from], to: frames[l.to], r: l.r.map(Math.round), kind: l.kind, via: l.via || l.label || '' }));
const flows = manifest.flows
  .filter((f) => f.steps.every((s) => frames[s.screen]))
  .map((f) => ({ name: f.title, start: frames[f.start] }));

process.stdout.write(`// generated by gen-prototype.mjs
${matcher}
const LINKS = ${JSON.stringify(wired)};
const FLOWS = ${JSON.stringify(flows)};
const page = await figma.getNodeByIdAsync(${JSON.stringify(pageId)});
await figma.setCurrentPageAsync(page);
const byFrame = {};
for (const l of LINKS) (byFrame[l.from] = byFrame[l.from] || []).push(l);
const result = { wired: 0, missing: [], byKind: {} };
for (const [frameId, list] of Object.entries(byFrame)) {
  const root = await figma.getNodeByIdAsync(frameId);
  const hit = matchAll(root, list.map((l) => ({ r: l.r, d: 0 })));
  const perNode = new Map();
  list.forEach((l, i) => {
    let n = hit.get(i);
    if (!n) { result.missing.push(root.name + ' → ' + l.via); return; }
    // a reaction on a layer inside an instance is an override; prefer the instance itself
    while (n.parent && n.parent.type === 'INSTANCE' && Math.abs(n.parent.width - n.width) < 1 && Math.abs(n.parent.height - n.height) < 1) n = n.parent;
    // the first link found for a layer wins: flow links come before global ones
    if (perNode.has(n.id)) return;
    perNode.set(n.id, { n, l });
  });
  for (const { n, l } of perNode.values()) {
    await n.setReactionsAsync([{ trigger: { type: 'ON_CLICK' }, actions: [{ type: 'NODE', destinationId: l.to, navigation: 'NAVIGATE',
      // the guide's motion: --dur-normal (.22s) on its --ease curve
      transition: { type: 'DISSOLVE', easing: { type: 'CUSTOM_CUBIC_BEZIER', easingFunctionCubicBezier: { x1: 0.22, y1: 0.61, x2: 0.36, y2: 1 } }, duration: 0.22 }, preserveScrollPosition: false, resetVideoPosition: false }] }]);
    result.wired++;
    result.byKind[l.kind] = (result.byKind[l.kind] || 0) + 1;
  }
}
page.flowStartingPoints = FLOWS.map((f) => ({ nodeId: f.start, name: f.name }));
result.flows = page.flowStartingPoints.length;
return result;
`);
