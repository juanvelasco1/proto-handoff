#!/usr/bin/env node
// Generates the use_figma script that names a captured screen's layers from its DOM map
// and tags component occurrences, so later steps can build and swap components.
//
//   node gen-annotate.mjs <map/NN-screen.json> <frameNodeId> [--lean] > annotate.figma.js
//
// Layer names after this step:
//   component root  → its component name, props kept in shared plugin data (ns "uic")
//   section         → its section name (rail, app-header, content…)
//   other container → its id or first class (what the prototype calls it)
//   text            → its own characters (Figma's default for text layers)
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const [mapFile, frameId] = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const here = path.dirname(fileURLToPath(import.meta.url));
const matcher = readFileSync(path.join(here, 'lib/figma-match.js'), 'utf8');
const map = JSON.parse(readFileSync(mapFile, 'utf8'));

// Keep containers and anything meaningful; bare text leaves are named from their characters.
// --lean keeps only components, sections, nav targets and their ancestors (the ancestors carry
// the drift the matcher needs), for screens whose full map would not fit in one call.
const lean = process.argv.includes('--lean');
const nodes = map.nodes;
let keepSet;
if (lean) {
  keepSet = new Set();
  const stack = [];
  nodes.forEach((n, i) => {
    stack.length = n.d;
    if (n.ui || n.section || n.nav || n.icon) { keepSet.add(i); for (const a of stack) keepSet.add(a); }
    stack[n.d] = i;
  });
}
const keep = nodes.filter((n, i) => {
  if (lean) return keepSet.has(i);
  const leaf = !(nodes[i + 1] && nodes[i + 1].d > n.d);
  return n.ui || n.section || n.nav || n.img || n.icon || !leaf;
});
const nameOf = (n) => (typeof n.icon === 'string' ? 'icon:' + n.icon : n.name);
const names = [...new Set(keep.map(nameOf))];
// Compact rows keep each call well under the tool's size limit: flat numbers only,
// [x, y, w, h, nameIdx, depth, propsIdx, slotsIdx]; props/slots live in lookup tables and
// only component roots carry the last two (-1 = no slots).
const props = [], slots = [];
const idx = (list, v) => { const k = JSON.stringify(v); let i = list.indexOf(k); if (i < 0) { list.push(k); i = list.length - 1; } return i; };
const rows = keep.map((n) => {
  const row = [...n.r.map(Math.round), names.indexOf(nameOf(n)), n.d];
  if (n.ui) row.push(idx(props, n.props || ''), n.slots ? idx(slots, n.slots) : -1);
  return row;
});

process.stdout.write(`// generated by gen-annotate.mjs for ${map.screen}
${matcher}
const NAMES = ${JSON.stringify(names)};
const PROPS = [${props.join(',')}];
const SLOTS = [${slots.join(',')}];
const ROWS = ${JSON.stringify(rows)}.map((a) => {
  const r = [a.slice(0, 4), a[4], a[5]];
  if (a.length > 6) r.push(PROPS[a[6]], a[7] < 0 ? 0 : SLOTS[a[7]]);
  return r;
});
const root = await figma.getNodeByIdAsync(${JSON.stringify(frameId)});
const entries = ROWS.map((r) => ({ r: r[0], d: r[2] }));
const hit = matchAll(root, entries);
let renamed = 0, components = 0;
const byUi = {};
ROWS.forEach((r, i) => {
  const n = hit.get(i);
  if (!n) return;
  n.name = NAMES[r[1]];
  renamed++;
  if (n.name.startsWith('icon:')) {
    // a glyph: tagged so build-icons.js can make it an Icon/<name> component
    n.setSharedPluginData('uic', 'icon', n.name.slice(5));
    n.name = 'icon/' + n.name.slice(5);
    return;
  }
  if (r.length > 3) {
    components++;
    n.setSharedPluginData('uic', 'ui', NAMES[r[1]]);
    n.setSharedPluginData('uic', 'props', r[3]);
    if (r[4]) n.setSharedPluginData('uic', 'slots', JSON.stringify(r[4]));
    byUi[NAMES[r[1]]] = (byUi[NAMES[r[1]]] || 0) + 1;
  }
});
let texts = 0;
for (const t of root.findAllWithCriteria({ types: ['TEXT'] })) {
  if (/^(Italic |Bold )?Text$/.test(t.name)) {
    t.name = t.characters.replace(/\\s+/g, ' ').trim().slice(0, 48) || 'Text';
    texts++;
  }
}
const missed = ROWS.map((r, i) => (hit.has(i) ? null : NAMES[r[1]])).filter(Boolean);
const missedUi = ROWS.filter((r, i) => r.length > 3 && !hit.has(i)).map((r) => NAMES[r[1]]);
return { screen: ${JSON.stringify(map.screen)}, entries: ROWS.length, matched: hit.size, renamed, texts, components, byUi,
  missedCount: missed.length, missedComponents: missedUi };
`);
